    public void status() {

        m = (Mascota) cboMascotas.getSelectedItem();
        if (m != null) {
            lblAlimentacion.setText(m.getAlimentacion() + "");
            lblEnergia.setText(m.getEnergia() + "");
            lblFelicidad.setText(m.getFelicidad() + "");
            lblMascota.setIcon(new javax.swing.ImageIcon(getClass().getResource("/GUI/img/" + m.getSkin() + "_64.png")));
        }

    }

